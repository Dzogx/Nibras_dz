async function seed() {
  try {
    const connection = await mysql.createConnection(DATABASE_URL);

    console.log('Seeding curriculum...');

    for (const doc of curriculumData) {
      try {
        await connection.execute(
          `INSERT INTO curriculumDocuments (title, type, subject, gradeLevel, content, sourceReference, unitNumber, lessonNumber) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
          [doc.title, doc.type, doc.subject, doc.gradeLevel, doc.content, doc.sourceReference, doc.unitNumber || null, doc.lessonNumber || null]
        );
        console.log(`  ✓ ${doc.title.substring(0, 60)}...`);
      } catch (e) {
        console.log(`  ✗ ${doc.title.substring(0, 40)}... (${e.message})`);
      }
    }

    const [rows] = await connection.execute('SELECT COUNT(*) as count FROM curriculumDocuments');
    console.log(`\nTotal documents: ${rows[0].count}`);

    await connection.end();
    console.log('Done!');
  } catch (error) {
    console.error('Error:', error.message);
    process.exit(1);
  }
}

seed();
