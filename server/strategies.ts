/** التمييز بين وضعية إدماجية وتعلّمية حسب العنوان والسياق */
export function detectSituationKind(title: string, context?: string): SituationKind {
  const hay = `${title} ${context ?? ""}`;
  if (/(إدماج|ادماج|وضعية\s+إدماجية|إدماجية|وضعيات\s+إدماج)/.test(hay)) return "integrative";
  return "learning";
}

/** استنتاج المادة من اسم الخطة السنوية */
export function normalizeSubject(subject: string): "history" | "geography" | "civics" {
  if (/تربية\s*مدنية|مدني/.test(subject)) return "civics";
  if (/جغرافيا/.test(subject)) return "geography";
  return "history";
}

